import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileMessage } from '@lingui/message-utils/compileMessage';

/*
 * ICU JSON in, compiled catalogs out.
 *
 * The parser is the expensive part of ICU, not the formatting: shipping it
 * costs 9.7 KB gzip, against 2.1 KB for `@lingui/core` running an already
 * compiled message. Doing it here means the browser never sees an ICU string.
 *
 * Catalogs are emitted one file per namespace so a page can load the four it
 * uses instead of all thirty. That split is not a micro-optimisation: it is
 * what kept the login page from carrying the copy for project deletion.
 */

const here = dirname(fileURLToPath(import.meta.url));
const messagesDir = join(here, '..', 'messages');
const outDir = join(here, '..', 'src', 'generated');

/** `{ a: { b: 'x' } }` becomes `{ 'a.b': 'x' }`, the shape the runtime keys on. */
function flatten(value, prefix = '', out = {}) {
  for (const [key, child] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (child && typeof child === 'object' && !Array.isArray(child)) {
      flatten(child, path, out);
    } else {
      out[path] = String(child);
    }
  }
  return out;
}

function namespaceOf(key) {
  const [head] = key.split('.');
  return head ?? 'common';
}

const locales = readdirSync(messagesDir)
  .filter((name) => name.endsWith('.json'))
  .map((name) => name.replace(/\.json$/, ''))
  .sort();

mkdirSync(outDir, { recursive: true });

const namespaces = new Set();
const keysByNamespace = new Map();

for (const locale of locales) {
  const source = JSON.parse(
    readFileSync(join(messagesDir, `${locale}.json`), 'utf8'),
  );
  const flat = flatten(source);

  const byNamespace = new Map();
  for (const [key, message] of Object.entries(flat)) {
    const ns = namespaceOf(key);
    namespaces.add(ns);
    if (!byNamespace.has(ns)) byNamespace.set(ns, {});

    try {
      byNamespace.get(ns)[key] = compileMessage(message);
    } catch (error) {
      throw new Error(
        `${locale}.json: ${key} is not valid ICU\n  ${message}\n  ${error.message}`,
      );
    }

    if (locale === 'en') {
      if (!keysByNamespace.has(ns)) keysByNamespace.set(ns, []);
      keysByNamespace.get(ns).push(key);
    }
  }

  mkdirSync(join(outDir, locale), { recursive: true });
  for (const [ns, catalog] of byNamespace) {
    writeFileSync(
      join(outDir, locale, `${ns}.ts`),
      `// Generated by scripts/compile-catalogs.mjs. Do not edit.\nexport default ${JSON.stringify(catalog)} as const;\n`,
    );
  }
}

const sorted = [...namespaces].sort();

// The loader is generated rather than written by hand so a new namespace in the
// JSON reaches the bundler without anyone remembering to register it. Static
// `import()` calls, so every one is a chunk the bundler can split.
const entries = sorted
  .map((ns) => {
    const arms = locales
      .map((l) => `    ${l}: () => import('./${l}/${ns}.js'),`)
      .join('\n');
    return `  '${ns}': {\n${arms}\n  },`;
  })
  .join('\n');

writeFileSync(
  join(outDir, 'catalogs.ts'),
  `// Generated by scripts/compile-catalogs.mjs. Do not edit.
import type { Locale } from '../locales.js';

type Loader = () => Promise<{ default: Record<string, unknown> }>;

export type Namespace = ${sorted.map((n) => `'${n}'`).join(' | ')};

export const NAMESPACES = [${sorted.map((n) => `'${n}'`).join(', ')}] as const;

export const catalogs: Record<Namespace, Record<Locale, Loader>> = {
${entries}
};
`,
);

const allKeys = [...keysByNamespace.values()].flat().sort();
writeFileSync(
  join(outDir, 'keys.ts'),
  `// Generated by scripts/compile-catalogs.mjs. Do not edit.
export type MessageKey =\n${allKeys.map((k) => `  | '${k}'`).join('\n')};\n`,
);

console.log(
  `i18n: ${allKeys.length} messages, ${sorted.length} namespaces, ${locales.length} locales`,
);
