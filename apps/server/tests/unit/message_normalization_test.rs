#[test]
fn matches_sentrys_parameterization_corpus() {
    let mut failures = vec![];
    for (name, input, expected) in CASES {
        let got = normalize_message_for_grouping(input);
        if got != *expected {
            failures.push(format!(
                "{name}\n     in: {input:?}\n   want: {expected:?}\n    got: {got:?}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} cases differ:\n\n{}",
        failures.len(),
        CASES.len(),
        failures.join("\n\n")
    );
}
